import { BbPage } from './src/bb.js';
const p = new BbPage();
await p.goto('https://www.g2.com/products/new');
await new Promise(r=>setTimeout(r,6000));
const url = p.url();
const body = p._bb('eval', 'document.body.innerText.substring(0,500)');
const loginBtns = p._bb('eval', `JSON.stringify(Array.from(document.querySelectorAll('button,a')).filter(el=>/google|sign in|login/i.test(el.textContent)||/google/i.test(el.href||'')).map(el=>({text:el.textContent.trim(),href:(el.href||'').substring(0,60)})).slice(0,5))`);
console.log('URL:', url.substring(0,80));
console.log('Login buttons:', loginBtns);
console.log('Body:', body.substring(0,300));
